/**
 * bun bench/compare.ts
 *
 * Compares each results file in bench/results/ with the file of the same
 * name in bench/results/baseline/: the same platform and machine only,
 * since timings from different hardware aren't comparable. Writes
 * bench/COMPARISON.md.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

interface Row { id: string; msMedian: number; msMin: number; msMax: number; peakMiBMedian: number | null; states: number[]; traces?: number[] }
interface Result { id: string; expect: string; comparable: boolean; problems: string[]; rows: Row[] }
interface File { environment: { date: string; commit: string; dirty: boolean; platform: string; machine?: string; runs: number }; results: Result[] }

const root = resolve(import.meta.dir, "..");
const dir = join(root, "bench", "results");
const read = (path: string): File => JSON.parse(readFileSync(path, "utf8")) as File;
const cell = (r: Row | undefined): string =>
  r === undefined ? "—" : `${r.msMedian.toFixed(0)} (${r.msMin.toFixed(0)}–${r.msMax.toFixed(0)}), ${r.peakMiBMedian === null ? "?" : r.peakMiBMedian.toFixed(0)} MiB`;

const sections = readdirSync(dir).filter((f) => f.endsWith(".json") && existsSync(join(dir, "baseline", f))).sort().map((f) => {
  const before = read(join(dir, "baseline", f));
  const after = read(join(dir, f));
  const heading = `## ${after.environment.platform}, ${after.environment.machine ?? "unknown machine"}`;
  if (after.environment.commit === before.environment.commit) return `${heading}\n\nNo measurement after the baseline on this platform yet.\n`;
  const lines = [heading, "",
    `Before: ${before.environment.commit} (${before.environment.date}). After: ${after.environment.commit}${after.environment.dirty ? " (uncommitted changes)" : ""} ` +
      `(${after.environment.date}). ${after.environment.runs} runs per route after a warm-up; median ms (minimum–maximum), median peak memory.`, ""];
  for (const a of after.results) {
    const b = before.results.find((x) => x.id === a.id);
    lines.push(`### \`${a.id}\` (${a.expect})`, "");
    if (!a.comparable || b === undefined || !b.comparable) {
      lines.push(`Not comparable: ${[...a.problems, ...(b?.problems ?? ["no baseline"])].join("; ")}.`, "");
      continue;
    }
    lines.push("| Route | Before | After |", "| --- | --- | --- |");
    const get = (rs: Row[], id: string): Row | undefined => rs.find((r) => r.id === id);
    lines.push(`| quint-ts (before: no cache; after: cache warm) | ${cell(get(b.rows, "quint-ts"))} | ${cell(get(a.rows, "quint-ts"))} |`);
    lines.push(`| quint-ts, cache off | — | ${cell(get(a.rows, "quint-ts-nocache"))} |`);
    for (const id of ["tla-ts", "tlc-qts", "tlc-apalache", "quint-verify-tlc"]) lines.push(`| ${id} | ${cell(get(b.rows, id))} | ${cell(get(a.rows, id))} |`);
    const states = (rs: Row[]): string => [...new Set(rs.flatMap((r) => r.states))].join("/");
    const traces = (rs: Row[]): string => [...new Set(rs.flatMap((r) => r.traces ?? []))].join("/");
    lines.push("", `Distinct states, every route: before ${states(b.rows)}, after ${states(a.rows)}.` +
      (a.expect === "violated" ? ` Counterexample length: before ${traces(b.rows) || "not recorded"}, after ${traces(a.rows)}.` : ""), "");
  }
  return lines.join("\n");
});

writeFileSync(join(root, "bench", "COMPARISON.md"), ["# Before and after", "",
  "Generated by `bun bench/compare.ts`; don't edit by hand. Each section compares one platform and machine with its own baseline",
  "(`bench/results/baseline/`), never with another machine. Before the change, quint-ts gave tla-ts a new compile-cache folder on",
  "every check, as `quint-ts, cache off` still does.", "", ...sections].join("\n"));
console.log(`bench/COMPARISON.md: ${sections.length} platform(s)`);
